#!/usr/bin/env python3
"""Generate paper/results.tex (LaTeX macros) from experiments/results/*.json.

The paper never contains typed numbers: every number comes from a macro defined here.

Naming:  experiments/results/ppo_baseline.json  {"return": {"mean": 12.345}}
         ->  \\resPpoBaselineReturnMean   (prefix "res" + CamelCase of file stem + key path)
Digits in names are spelled out (LaTeX macro names are letters only): seed42 -> SeedFourTwo.

Per-file formatting (optional, keys starting with "_" are never turned into macros):
    "_format": {"return.mean": ".1f", "success_rate": "pct1"}   # pct1 = x*100 with 1 decimal + "\\%"
    "_precision": 3                                             # default decimals for floats in this file

Usage:
    python scripts/make_results_tex.py              # write paper/results.tex
    python scripts/make_results_tex.py --check      # exit 1 if paper/results.tex is out of date (CI)
    python scripts/make_results_tex.py --lint-paper # warn about typed numbers in paper/*.tex
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS_DIR = ROOT / "experiments" / "results"
OUT = ROOT / "paper" / "results.tex"
PAPER_DIR = ROOT / "paper"
DEFAULT_PRECISION = 2

DIGITS = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]
LATEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
                 "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def camel(part: str) -> str:
    words = re.split(r"[^A-Za-z0-9]+", part)
    out = []
    for w in words:
        if not w:
            continue
        # split letter/digit runs so "seed42" -> "seed", "42"
        for chunk in re.findall(r"[A-Za-z]+|[0-9]+", w):
            if chunk.isdigit():
                out.append("".join(DIGITS[int(d)] for d in chunk))
            else:
                out.append(chunk[0].upper() + chunk[1:])
    return "".join(out)


def escape_tex(s: str) -> str:
    return "".join(LATEX_SPECIAL.get(c, c) for c in s)


def fmt_value(value, spec: str | None, precision: int) -> str:
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int) and spec is None:
        return f"{value:,}".replace(",", "{,}")
    if isinstance(value, (int, float)):
        if spec and spec.startswith("pct"):
            decimals = int(spec[3:] or 0)
            return f"{value * 100:.{decimals}f}\\%"
        if spec:
            return format(value, spec).replace(",", "{,}")
        return f"{value:.{precision}f}"
    return escape_tex(str(value))


def flatten(obj, path=()):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if str(k).startswith("_"):
                continue
            yield from flatten(v, path + (str(k),))
    elif isinstance(obj, list):
        return  # lists (e.g. per-seed arrays) are raw data, not paper numbers
    elif obj is not None:
        yield path, obj


def build() -> str:
    macros: dict[str, tuple[str, str]] = {}
    files = sorted(RESULTS_DIR.rglob("*.json")) if RESULTS_DIR.exists() else []
    lines = [
        "% AUTO-GENERATED by scripts/make_results_tex.py -- DO NOT EDIT.",
        "% Source: experiments/results/*.json. Regenerate: python scripts/make_results_tex.py",
        "",
    ]
    for f in files:
        rel = f.relative_to(ROOT).as_posix()
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            sys.exit(f"ERROR: {rel} is not valid JSON: {e}")
        if not isinstance(data, dict):
            sys.exit(f"ERROR: {rel} must contain a JSON object at top level")
        formats = data.get("_format", {}) or {}
        precision = int(data.get("_precision", DEFAULT_PRECISION))
        stem = camel(f.relative_to(RESULTS_DIR).with_suffix("").as_posix())
        lines.append(f"% --- {rel}")
        for path, value in flatten(data):
            name = "res" + stem + "".join(camel(p) for p in path)
            if not re.fullmatch(r"[A-Za-z]+", name):
                sys.exit(f"ERROR: cannot build a LaTeX macro name from {rel}:{'.'.join(path)}")
            if name in macros:
                sys.exit(f"ERROR: macro \\{name} from {rel} collides with one from {macros[name][1]}")
            text = fmt_value(value, formats.get(".".join(path)), precision)
            macros[name] = (text, rel)
            lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
        lines.append("")
    if not files:
        lines.append("% (no results files yet)")
    return "\n".join(lines).rstrip() + "\n"


NUM_RE = re.compile(r"(?<![\\\w{.])(\d+\.\d+|\d+\s*\\%)")
UNIT_RE = re.compile(r"^\s*(pt|cm|mm|in|em|ex|bp|\\(line|text|column)width|\\(text)?height)")


def lint_paper() -> int:
    warnings = 0
    for tex in sorted(PAPER_DIR.rglob("*.tex")):
        if tex.name in {"results.tex", "diff.tex"}:
            continue
        for i, line in enumerate(tex.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            code = re.split(r"(?<!\\)%", line, maxsplit=1)[0]
            for m in NUM_RE.finditer(code):
                if UNIT_RE.match(code[m.end():]):
                    continue
                warnings += 1
                print(f"{tex.relative_to(ROOT).as_posix()}:{i}: typed number '{m.group(0)}' -- use a \\res... macro")
    print(f"lint-paper: {warnings} typed number(s) found")
    return warnings


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if paper/results.tex is stale")
    ap.add_argument("--lint-paper", action="store_true", help="warn about typed numbers in paper/*.tex")
    ap.add_argument("--strict", action="store_true", help="with --lint-paper: exit 1 if any are found")
    args = ap.parse_args()

    if args.lint_paper:
        n = lint_paper()
        return 1 if (args.strict and n) else 0

    content = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != content:
            print("paper/results.tex is out of date: run python scripts/make_results_tex.py and commit it")
            return 1
        print("paper/results.tex is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8", newline="\n")
    n = content.count("\\newcommand")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()} ({n} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
